"""OpenStack Expert Agent (v0.6, docs/architecture/adr-0008-openstack-
expert-agent.md) -- "the system starts teaching, not just reporting."

Every prior agent reports a finding (a number, a flagged metric, a
correlated log line). This agent's job is different: given a finding, or
given a direct question, it looks up the matching entry in
openstack_expert_catalog.CATALOG and answers with the fixed 3-layer shape
every entry is authored in:

1. **What's happening** -- the general mechanism behind this symptom
   (`entry["what_it_means"]`), prefixed with the concrete evidence that
   triggered it when there is any (a specific metric value, a specific log
   line) so the answer teaches the *general* pattern while staying
   anchored to *this* incident.
2. **How to confirm it yourself** -- `entry["confirm_commands"]`, always
   read-only, always rendered verbatim (never paraphrased or generated by
   an LLM -- an operational command is either exactly correct or actively
   harmful to trust, there's no room for a fluent-but-wrong version).
3. **What's usually done about it** -- `entry["remediation_commands"]`, a
   mix of read-only and state-changing, each labeled explicitly.

Two ways into this agent, distinguished by what's already in `state` when
it runs (see graph.py):

- **Chained**: routed here automatically straight after anomaly_agent,
  monitoring_agent, or (v0.9) network_agent produced a real finding (see
  should_trigger_after_anomaly/should_trigger_after_monitoring/
  should_trigger_after_network, which graph.py's conditional edges call).
  `state["target_agent"]` is still "anomaly"/"monitoring"/"network" at
  that point -- this agent reads that to know it's chained, and to know
  which upstream `raw_data` shape to pull evidence from, then overwrites
  `target_agent` to "openstack_expert" once it has produced its own
  result (the original diagnosis's `raw_data` is nested under
  `diagnosed_by`/`upstream_summary` in the new result, never discarded).
- **Standalone**: routed here directly by the router for a direct
  "how do I check X" / "how do I fix Y" question with no upstream
  diagnosis -- `state["target_agent"]` is already "openstack_expert" on
  entry, set by intent_router.py, and there is no `agent_result` yet.

Both paths converge on the same `_match_symptoms` -> `_render_answer`
pipeline; only how the matcher's inputs (metric name, service binaries,
free-text keywords, log line content) get assembled differs.

v0.9 adds a third chaining source: network_agent (nodes/network.py). Its
finding's `raw_data["neutron_signal"]["down_agents"]` maps straight onto
`service_binaries` (a Neutron agent's `binary`, e.g. "neutron-l3-agent"),
which is exactly what the catalog's neutron-dhcp-agent-down/
neutron-l3-agent-down/neutron-ovs-agent-down entries already match on --
those entries existed since before this agent had any live trigger for
them (openstack_expert_catalog.py ships with every service-agent entry
up front), so this is purely a new `_evidence_from_*` extractor plus one
more `should_trigger_after_*` gate, no new catalog content.

v0.10 (Phase C) widens that same network_agent chaining source: its
finding can now come from an entity-scoped read (a network/subnet/
instance question, not a node one -- see nodes/network.py's own v0.10
note) with no Neutron *agent* involved at all, so `_evidence_from_network`
now also recognizes a down/disabled Neutron port and an instance stuck in
ERROR alongside one, via the two new catalog entries (`port-down`,
`instance-stuck-in-error`) this version adds.

v1.0 (docs/architecture/adr-0010-openstack-expert-v1-expansion.md) adds
two things, both scoped to what the original v0.6/v0.9/v0.10 design left
as explicit follow-ups (adr-0008 §OS.4-OS.6):

- **The matcher's `catalog` is no longer just the static CATALOG list.**
  `_combined_catalog` appends every currently-"published" feedback-loop
  entry (agents/nodes/openstack_expert_catalog_store.py, backed by
  models.CatalogEntry) on every call, so an incident type that got
  resolved and turned into a catalog entry from the UI now matches the
  next time it recurs -- chained or standalone -- without a code change
  or a restart. `_match_symptoms`/`_detect_service_binaries` both take an
  explicit `catalog` argument (default: just the static CATALOG, so
  every v0.6-era direct unit test of either function is unaffected).
- **Standalone no-match now falls through two more tiers** before giving
  up (`_standalone_fallback`): official OpenStack documentation
  (services/openstack_docs/search.py, a separate Qdrant collection from
  both this catalog and the internal RAG/Knowledge Agent's own corpus --
  see that module's docstring) and, below that, a community web search
  (services/web_search.py, biased toward Launchpad/mailing-list/Q&A
  sources). Each tier is visibly labeled by source ("catalog" /
  "official_docs" / "web_search" / "none" in `raw_data["source"]`, and in
  the rendered markdown itself) so nobody mistakes a Launchpad forum post
  for either this deployment's curated catalog or actual upstream docs.
  Deliberately standalone-only: a *chained* no-match still leaves the
  upstream diagnosis as the final answer unmodified (see `_run_chained`'s
  own comment) -- that v0.6 decision (adr-0008 decision #4) is preserved
  as-is here, not widened, since a good specific diagnosis still beats a
  generic-but-sourced layer stacked on top of it.
"""
