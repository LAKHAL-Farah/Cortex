# Built from the catalog itself (not hand-duplicated) so a new entry's
# service_binaries automatically become recognizable in free text without
# a second list to keep in sync.
_ALL_SERVICE_BINARIES = sorted({b for entry in CATALOG for b in entry["service_binaries"]})

# A live/monitoring metric has to clear this before it's worth treating as
# "the thing to explain" rather than normal variation -- same threshold
# anomaly.py's own live-read fallback and monitoring's system prompt use
# ("call out anything above ~90%"), kept slightly under that so the expert
# agent still fires on a monitoring-flagged "concerning" reading.
_METRIC_TRIGGER_THRESHOLD = 85.0

# Score weights for the symptom matcher -- a metric-name or service-binary
# hit is a structured, unambiguous signal (worth more) than a keyword
# appearing somewhere in free text, and a keyword in the *question itself*
# is worth more than the same keyword merely appearing in a log line (the
# latter is corroborating, not the actual ask).
_SCORE_METRIC_NAME = 3
_SCORE_SERVICE_BINARY = 3
_SCORE_KEYWORD_IN_QUERY = 2
# Weighted equal to a query-keyword hit, not lower: a keyword actually
# found in real log content is concrete corroborating evidence, not a
# guess -- and this is what lets a specific log pattern (e.g. "lost
# connection to libvirt") outrank a bare metric-name match (e.g.
# "cpu_usage") when both are present, matching anomaly.py's own
# _hypothesize_cause philosophy that log content is the more specific
# signal when it's available.
_SCORE_KEYWORD_IN_LOG_LINE = 2

# Placeholders in catalog commands that are safe to fill in with a
# concretely-known hostname -- anything else (<instance_id>, <volume_id>,
# <agent_id>, ...) is left as a placeholder since this agent never has
# that specific a value on hand.
_HOST_PLACEHOLDERS = re.compile(r"<host>|<hostname>|<hypervisor_hostname>")


